#!/usr/bin/env bun
/**
 * Renders the web document's security headers as nginx snippets (Issue #127).
 *
 * The SPA is served by nginx, not by the Hono server, so the server's
 * `securityHeadersMiddleware` never reaches the HTML document. This script
 * reuses {@link buildSecurityHeaders} — the single source of the policy — and
 * writes one `add_header` snippet per CSP mode. The web image's entrypoint
 * (`apps/web/docker-entrypoint.d/40-csp-mode.sh`) selects one at container
 * start from `CSP_MODE`, so the rollback lever matches the server's.
 *
 * The web and API are split-origin, so the API origin (`VITE_SERVER_URL`) is
 * added to `connect-src`, and the enforced policy reports to the server's sink.
 *
 * Usage: bun scripts/render-web-security-headers.ts <out-dir>
 */
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

import { errorReportingOrigin } from "../packages/observability/src/error-reporting";
import { buildSecurityHeaders, type CspMode } from "../packages/observability/src/security-headers";

/** Mirrors `CSP_REPORT_PATH` in `apps/server/src/security-csp-report.ts` (asserted by the test). */
export const CSP_REPORT_PATH = "/api/security/csp-report";

export const CSP_MODES: readonly CspMode[] = ["enforce", "report-only"];

/** Normalises `VITE_SERVER_URL` to an origin, failing closed on anything else. */
export function serverOriginFrom(serverUrl: string | undefined): string {
  let url: URL;
  try {
    url = new URL(serverUrl ?? "");
  } catch {
    throw new Error("VITE_SERVER_URL must be an absolute http(s) URL");
  }
  if (url.protocol !== "http:" && url.protocol !== "https:") {
    throw new Error("VITE_SERVER_URL must be an absolute http(s) URL");
  }
  return url.origin;
}

/** Quotes a header value for nginx, refusing characters nginx would interpret. */
function nginxQuote(value: string): string {
  if (/[$\\\r\n]/.test(value)) {
    throw new Error("security header value contains a character nginx cannot quote safely");
  }
  return `"${value.replaceAll('"', '\\"')}"`;
}

/**
 * Renders the `add_header` snippet for one CSP mode. `sentryDsn` (Issue #54)
 * adds only that DSN's origin to `connect-src` when browser error reporting is on.
 */
export function renderSnippet(cspMode: CspMode, serverOrigin: string, sentryDsn?: string): string {
  const headers = buildSecurityHeaders({
    cspMode,
    allowDevScriptEval: false,
    reportToGroup: "csp-endpoint",
    reportToUrl: `${serverOrigin}${CSP_REPORT_PATH}`,
    additionalConnectSrc: sentryDsn?.trim()
      ? [serverOrigin, errorReportingOrigin(sentryDsn.trim())]
      : [serverOrigin],
  });
  const lines = Object.entries(headers).map(
    ([name, value]) => `add_header ${name} ${nginxQuote(value)} always;`,
  );
  return `# Generated by scripts/render-web-security-headers.ts (${cspMode}). Do not edit.\n${lines.join("\n")}\n`;
}

if (import.meta.main) {
  const outDir = process.argv[2];
  if (!outDir) {
    console.error("usage: bun scripts/render-web-security-headers.ts <out-dir>");
    process.exit(2);
  }
  const serverOrigin = serverOriginFrom(process.env.VITE_SERVER_URL);
  await mkdir(outDir, { recursive: true });
  for (const cspMode of CSP_MODES) {
    await writeFile(
      join(outDir, `security-headers.${cspMode}.conf`),
      renderSnippet(cspMode, serverOrigin, process.env.VITE_SENTRY_DSN),
    );
  }
  console.log(`Wrote web security-header snippets for ${serverOrigin}`);
}
