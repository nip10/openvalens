/**
 * Writes packages/i18n/src/safety-ids.ts from the English catalog (#67).
 *
 * A message is safety-critical when its macro carries `comment: "safety"`
 * (extracted as `#. safety`). Those ids stay English in any locale until a
 * reviewer approves them (see packages/i18n/src/catalogs.ts).
 *
 *   bun scripts/i18n-safety-ids.ts          # write
 *   bun scripts/i18n-safety-ids.ts --check  # fail if the file is stale
 */
import { readFileSync, writeFileSync } from "node:fs";
import { generateMessageId } from "@lingui/message-utils/generateMessageId";

const PO = "packages/i18n/src/locales/en/messages.po";
const OUT = "packages/i18n/src/safety-ids.ts";

/** Reads a (possibly multi-line) PO string value starting at `lines[index]`. */
function readValue(lines: string[], index: number, keyword: string): string {
  const first = lines[index]!.slice(keyword.length + 1).trim();
  const parts = [first];
  for (let next = index + 1; next < lines.length && lines[next]!.startsWith('"'); next++)
    parts.push(lines[next]!.trim());
  return parts.map((part) => JSON.parse(part) as string).join("");
}

export function safetyIds(po: string): string[] {
  const ids = new Set<string>();
  for (const block of po.split(/\n\s*\n/)) {
    const lines = block.split("\n");
    const comments = lines
      .filter((line) => line.startsWith("#."))
      .map((line) => line.slice(2).trim());
    if (!comments.includes("safety")) continue;
    const msgid = lines.findIndex((line) => line.startsWith("msgid "));
    if (msgid === -1) continue;
    const message = readValue(lines, msgid, "msgid");
    const contextAt = lines.findIndex((line) => line.startsWith("msgctxt "));
    const context = contextAt === -1 ? "" : readValue(lines, contextAt, "msgctxt");
    ids.add(
      comments.includes("js-lingui-explicit-id") ? message : generateMessageId(message, context),
    );
  }
  return [...ids].sort();
}

function render(ids: string[]): string {
  return `// Generated by scripts/i18n-safety-ids.ts from the English catalog. Do not edit.
/** Message ids tagged \`safety\`: English until a reviewer approves them per locale. */
export const SAFETY_MESSAGE_IDS: ReadonlySet<string> = new Set<string>(${JSON.stringify(ids, null, 2)});
`;
}

if (import.meta.main) {
  const next = render(safetyIds(readFileSync(PO, "utf8")));
  if (process.argv.includes("--check")) {
    const current = readFileSync(OUT, "utf8");
    if (current !== next) {
      console.error(`${OUT} is stale. Run: bun scripts/i18n-safety-ids.ts`);
      process.exit(1);
    }
  } else writeFileSync(OUT, next);
}
