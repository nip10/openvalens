/**
 * Mirrors the Bloom colour tokens from packages/ui/src/styles/tokens.css into
 * apps/native/global.css as uniwind light/dark theme variants.
 *
 * Why: tokens.css declares light values on `:root` and dark ones on `.dark`,
 * which suits the web. uniwind (and heroui-native's `useThemeColor`) only see
 * variables declared under `@variant light` / `@variant dark`, and
 * heroui-native's own theme declares `--background`, `--muted`, `--accent`
 * and friends there, which otherwise win over Bloom's. This block puts every
 * Bloom value where native reads it.
 *
 *   bun scripts/theme-tokens.ts          rewrite the block in global.css
 *   bun scripts/theme-tokens.ts --check  exit 1 if it is out of date
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dir, "..");
const TOKENS = join(ROOT, "../../packages/ui/src/styles/tokens.css");
const GLOBAL = join(ROOT, "global.css");
const BEGIN = "/* BEGIN generated by scripts/theme-tokens.ts; do not edit by hand */";
const END = "/* END generated theme tokens */";

function declarations(css: string, selector: ":root" | ".dark"): [string, string][] {
  const out: [string, string][] = [];
  const pattern = new RegExp(`(^|\\n)${selector.replace(".", "\\.")} \\{([^}]*)\\}`, "g");
  for (const block of css.matchAll(pattern)) {
    for (const line of block[2]!.split("\n")) {
      const match = /^\s*(--[a-z0-9-]+):\s*(#[0-9a-fA-F]{3,8});/.exec(line);
      if (match) out.push([match[1]!, match[2]!]);
    }
  }
  return out;
}

/** Every `--color-*` utility tokens.css maps, with its source, e.g. `--color-sleep` → `--tone-sleep`. */
function colorMappings(css: string): [string, string][] {
  const pairs = new Map<string, string>();
  for (const m of css.matchAll(/^\s*(--color-[a-z0-9-]+):\s*var\((--[a-z0-9-]+)\);/gm)) {
    pairs.set(m[1]!, m[2]!);
  }
  return [...pairs];
}

export function renderThemeBlock(tokensCss: string): string {
  const light = declarations(tokensCss, ":root");
  const darkMap = new Map(declarations(tokensCss, ".dark"));
  const known = new Set(light.map(([name]) => name));
  // `static` makes each colour readable from JS (useThemeColor / useCSSVariable)
  // even when no className uses it yet.
  const lines = [BEGIN, "@theme inline static {"];
  for (const [name, source] of colorMappings(tokensCss)) {
    if (known.has(source)) lines.push(`  ${name}: var(${source});`);
  }
  lines.push("}", "", "@layer theme {", "  :root {", "    @variant light {");
  for (const [name, value] of light) lines.push(`      ${name}: ${value};`);
  lines.push("    }", "    @variant dark {");
  for (const [name, value] of light) lines.push(`      ${name}: ${darkMap.get(name) ?? value};`);
  lines.push("    }", "  }", "}", END);
  return lines.join("\n");
}

export function syncGlobalCss(globalCss: string, tokensCss: string): string {
  const block = renderThemeBlock(tokensCss);
  const start = globalCss.indexOf(BEGIN);
  const end = globalCss.indexOf(END);
  if (start === -1 || end === -1) return `${globalCss.trimEnd()}\n\n${block}\n`;
  return globalCss.slice(0, start) + block + globalCss.slice(end + END.length);
}

if (import.meta.main) {
  const tokensCss = readFileSync(TOKENS, "utf8");
  const current = readFileSync(GLOBAL, "utf8");
  const next = syncGlobalCss(current, tokensCss);
  if (process.argv.includes("--check")) {
    if (next !== current) {
      console.error("apps/native/global.css is out of date: run bun scripts/theme-tokens.ts");
      process.exit(1);
    }
  } else if (next !== current) {
    writeFileSync(GLOBAL, next);
  }
}
